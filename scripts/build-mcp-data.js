#!/usr/bin/env node
/**
 * Writes api/_data/quotes.js, the library the MCP server (api/mcp.js) answers
 * from: every cited passage in constants/stoicQuotes.js and every published
 * misattribution in constants/misattributions.js.
 *
 * Generated rather than read at request time because the constants are app
 * modules, not something a serverless function can load cheaply, and a
 * committed file is what Vercel will actually bundle. The cost is that it can
 * go stale, so scripts/check.js rebuilds it in memory and fails if the
 * committed copy differs. A quote added to the app and missing from the
 * ChatGPT app would be the checker telling people a real quote is unknown.
 *
 *   node scripts/build-mcp-data.js
 */
const fs = require('fs');
const path = require('path');
const { loadModule } = require('./build-quote-checker');

const ROOT = path.join(__dirname, '..');
const OUT = path.join(ROOT, 'api', '_data', 'quotes.js');

function data() {
  const { STOIC_QUOTES } = loadModule('stoicQuotes.js', ['STOIC_QUOTES']);
  const { MISATTRIBUTIONS } = loadModule('misattributions.js', ['MISATTRIBUTIONS']);
  return {
    corpus: STOIC_QUOTES.map(q => ({
      id: q.id, quote: q.quote, author: q.author, work: q.work || '', section: q.source || '',
      themes: q.themes || [], virtues: q.virtues || [],
    })),
    mis: MISATTRIBUTIONS.map(m => ({
      id: m.id, text: m.text, credited: m.credited, actual: m.actual || '', note: m.note, confidence: m.confidence,
    })),
  };
}

function source() {
  return '// GENERATED by scripts/build-mcp-data.js from constants/stoicQuotes.js and\n' +
    '// constants/misattributions.js. Do not edit; edit those and rebuild.\n' +
    'export const DATA = ' + JSON.stringify(data(), null, 1) + ';\n';
}

if (require.main === module) {
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, source());
  const d = data();
  console.log(`Built ${path.relative(ROOT, OUT)}: ${d.corpus.length} passages, ${d.mis.length} misattributions`);
}

module.exports = { source, OUT };
